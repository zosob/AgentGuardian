from __future__ import annotations

from typing import Any, Dict


def generate_markdown_report(profile: Dict[str, Any], result: Dict[str, Any], ollama_summary: str | None = None) -> str:
    """Generate a downloadable Markdown security report."""
    risks_md = ""
    for risk in result.get("risks", []):
        risks_md += f"- **{risk['category']}** ({risk['severity']}): {risk['reason']}\n"

    if not risks_md:
        risks_md = "- No major risks detected.\n"

    recommendations_md = ""
    for index, recommendation in enumerate(result.get("recommendations", []), start=1):
        recommendations_md += f"{index}. {recommendation}\n"

    if not recommendations_md:
        recommendations_md = "No recommendations generated.\n"

    category_md = ""
    for category, value in result.get("category_scores", {}).items():
        category_md += f"- **{category}:** {value}\n"

    report = f"""# AgentGuardian Security Risk Report

## Agent Profile

**Agent Name:** {profile.get('agent_name', 'Unnamed Agent')}

**Purpose:**  
{profile.get('agent_purpose', 'Not provided')}

**Tools:** {', '.join(profile.get('tools', [])) if profile.get('tools') else 'None selected'}

**Data Types:** {', '.join(profile.get('data_types', [])) if profile.get('data_types') else 'None selected'}

**External Inputs:** {', '.join(profile.get('external_inputs', [])) if profile.get('external_inputs') else 'None selected'}

**Autonomy Level:** {profile.get('autonomy_level', 'Not provided')}

**Human Approval:** {profile.get('human_approval', 'Not provided')}

---

## Risk Summary

**Risk Score:** {result['score']}/100

**Risk Level:** {result['risk_level']}

---

## Risk Category Breakdown

{category_md}

---

## Detected Risks

{risks_md}

---

## Recommended Controls

{recommendations_md}
"""

    if ollama_summary:
        report += f"""
---

## Local LLM Security Analysis

{ollama_summary}
"""

    report += """
---

## Disclaimer

This report is generated by AgentGuardian as a lightweight security review aid. It does not replace a formal security assessment, threat model, penetration test, privacy review, or compliance audit.
"""
    return report
